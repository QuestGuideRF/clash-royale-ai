    def __init__ (self ):
        """Инициализация"""
        pass
    def get_guide (self ,guide_id :str )->Dict :
        """Получение руководства"""
        return self .GUIDES .get (guide_id ,{})
    def get_all_guides (self )->Dict :
        """Получение всех руководств"""
        return self .GUIDES
    def get_guides_by_difficulty (self ,difficulty :str )->List [Dict ]:
        """Получение руководств по сложности"""
        return [
        {'id':k ,**v }
        for k ,v in self .GUIDES .items ()
        if v .get ('difficulty')==difficulty
        ]
    def search_guides (self ,query :str )->List [Dict ]:
        """
        Поиск по руководствам
        Args:
            query: Поисковый запрос
        """
        query =query .lower ()
        results =[]
        for guide_id ,guide in self .GUIDES .items ():
            if (query in guide .get ('title','').lower ()or
            query in guide .get ('content','').lower ()):
                results .append ({'id':guide_id ,**guide })
        return results
    def get_tips (self ,guide_id :str )->List [str ]:
        """Получение советов из руководства"""
        guide =self .get_guide (guide_id )
        return guide .get ('tips',[])
