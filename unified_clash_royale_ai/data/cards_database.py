def get_card_info (card_name :str )->dict :
    card_name =card_name .lower ().replace (" ","_").replace (".","")
    return CARDS_DATABASE .get (card_name ,None )
def get_cards_by_type (card_type :str )->list :
    return [name for name ,data in CARDS_DATABASE .items ()if data .get ('type')==card_type ]
def get_cards_by_tag (tag :str )->list :
    return [name for name ,data in CARDS_DATABASE .items ()if tag in data .get ('tags',[])]
def get_cards_by_elixir (elixir :int )->list :
    return [name for name ,data in CARDS_DATABASE .items ()if data .get ('elixir')==elixir ]
def get_counter_cards (target_card :str )->list :
    card_info =get_card_info (target_card )
    if not card_info :
        return []
    counters =[]
    tags =card_info .get ('tags',[])
    if 'tank'in tags :
        counters .extend (get_cards_by_tag ('tank_killer'))
    if 'swarm'in tags :
        counters .extend (get_cards_by_tag ('area_damage'))
    if 'air'in tags :
        for name ,data in CARDS_DATABASE .items ():
            if data .get ('targets')in ['air_ground','air']:
                counters .append (name )
    return list (set (counters ))